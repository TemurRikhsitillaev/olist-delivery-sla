-- 6. Цена сокращения обещания
-- ------------------------------------------------------------

--Как отразится сокращение обещанного срока на доле опозданий.
--Из доехавших вовремя заказов смотрим, у скольких запас до обещанной даты меньше срезаемого числа дней; они становятся опозданиями.
--cut_days - сколько дней срезать. Срезание одного дня выводит из "вовремя" только заказы с нулевым запасом.

SELECT -days_vs_estimate + 1 AS cut_days, COUNT(*) AS orders_count,
    SUM(COUNT(*)) OVER (ORDER BY -days_vs_estimate + 1) AS will_be_late,
    ROUND((SUM(COUNT(*)) OVER (ORDER BY -days_vs_estimate + 1)
       + (SELECT COUNT(*) FROM delivered_orders WHERE is_late)) /
       (SELECT COUNT(*) FROM delivered_orders) * 100, 2)
    AS will_be_late_pct
FROM delivered_orders
WHERE is_late = FALSE
GROUP BY cut_days
ORDER BY cut_days
LIMIT 7;

