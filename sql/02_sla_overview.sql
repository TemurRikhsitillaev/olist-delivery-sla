-- вырастет с 6.79% до 15.05%. Один день стоит 1.34 пункта, пятый - 1.99, седьмой - 3.76. Срезание трёх
-- дней почти удваивает долю опозданий (с 6.79% до 11.26%). Запас 13 дней выглядит ресурсом, но им
-- нельзя распорядиться. Срезать можно день-два, дальше процент опозданий растёт быстрее, чем линейно.
