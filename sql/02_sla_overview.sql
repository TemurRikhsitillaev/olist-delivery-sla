-- 96 203 доставленных заказа бразильского маркетплейса Olist за 20 месяцев, с января 2017 года по август 2018 года.

-- Типичный заказ доезжает за 10 дней, но 9 из 10 заказов доезжают за 23 дня или быстрее. 6 531 заказ, или 6.79%, приехал
-- позже обещанной даты. Три заказа из ста приезжают больше чем на неделю позже обещанного. Но это усреднение по периоду,
-- внутри которого месяцы отличаются в шестнадцать раз, от 1.16% до 18.96%.

-- Главная находка. Доля опозданий зависит не только от скорости доставки, но и от того, какую дату компания обещает,
-- причём второе работает быстрее.
-- Ноябрь 2017 - объём вырос в 1.6 раза под чёрную пятницу, обещанную дату оставили прежней (23 дня), доставка
-- замедлилась. 12.40% опозданий.
-- Февраль - март 2018 - p90 доставки вырос с обычных 23 до 31 и 32, а обещание в это же время ужали с 26 в январе до 22 дней. Февраль 14.13%, март 18.96% (худший).
-- Июнь и август 2018 - медиана 8 против 7, p90 16 против 13. В июне обещали 28 дней, а в августе 14. Результат: 1.16% против 6.19%.
-- Высокий процент "вовремя" не обязательно означает хорошую работу логистики - его можно получить, просто пообещав
-- побольше.

-- Обещание перед пиком надо приводить в соответствие с реальной скоростью. Ноябрь 2017 года показал, что под пиковыми нагрузками
-- доля опозданий выросла втрое, с 4.18% в октябре до 12.40%. Компания знала про пик за месяцы, но
-- медиана обещаний не изменилась (23 дня). Сверх октябрьского уровня - 600 из 904 опозданий.
-- Если целью поставить долю опозданий спокойных месяцев (3-4%), обещание должно покрывать примерно p97 доставки - а это 41 день против стоявших 23. 41 день -
-- это длинный срок, который может отпугивать покупателей. Расширение обещания не решает проблему, но меняет, кому достаётся ущерб.
-- Либо покупателю, который увидел 41 день и ушёл, либо покупателю, которому пообещали 23 дня и привезли позже.
-- Настоящая причина, похоже, - нехватка пропускной способности: объём вырос в 1.6 раза, p97 доставки - с 29 до 41.

-- Февраль-март 2018 года. Заказов в феврале 6555, доля опозданий 14.13%. Заказов в марте 7003, доля опозданий 18.96%.
-- Нагрузка такая же, как в январе (7069 заказов, 5.70% опозданий) и в апреле (6798 заказов, 4.50% опозданий) того же года,
-- но опоздания самые высокие за весь период. За эти месяцы p90 вырос с обычных 23 до 31 и 32. В ноябре компания получила
-- долю опозданий 12.40% на нетронутом обещании. В декабре расширилось обещание (с 23 до 28) и выправилась доставка (p97 с 41 до 39).
-- Падение до 7.46% - результат обоих. В январе понизили обещание (с 28 до 26), заказы увеличились, выправилась доставка
-- (p97 с 39 до 37) и доля опозданий сократилась. В феврале обещание сократилось (с 26 до 25), ухудшилась доставка (p97 с 37 до 44)
-- и доля опозданий подскочила (с 5.70% до 14.13%), почти в 2.5 раза. В марте ещё раз сократили обещание (с 25 до 22),
-- доставка осталась прежней (p97 44) и доля опозданий поднялась (с 14.13% до 18.96%). Март стал худшим месяцем периода.
-- Причина обвала в доставке не установлена, нужны внешние сведения (перевозчики, схема логистики, обстановка в стране).

-- Точность оценки. Типичный заказ, который не опоздал, доезжает на 13 дней раньше обещанного.
-- Каждый десятый покупатель видит обещание 35 дней и больше, хотя 9 из 10 заказов доезжают за 23 дня.
-- Решение о покупке принимается в том числе по этой дате. Сколько покупателей увидели её и ушли,
-- посчитать нельзя - данных о них нет.

