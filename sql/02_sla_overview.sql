	SELECT
		CASE
			WHEN days_vs_estimate BETWEEN 1 AND 3 THEN '1-3'
			WHEN days_vs_estimate BETWEEN 4 AND 7 THEN '4-7'
			WHEN days_vs_estimate BETWEEN 8 AND 14 THEN '8-14'
