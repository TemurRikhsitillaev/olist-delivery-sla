-- Опирается на delivered_orders из 02_sla_overview.sql.
-- Вопрос: какой этап сломался в феврале-марте 2018.
-- Сумма p90 этапов не равна p90 цикла, перцентили не складываются,
-- потому что долгий транзит и долгая передача приходятся на разные заказы.

SELECT purchase_month,
	COUNT(*) AS orders_count,
	ROUND(PERCENTILE_CONT(0.9) WITHIN GROUP (ORDER BY approve_hours)::numeric / 24, 2) AS p90_approve_days,
	COUNT(*) - COUNT(handover_days) AS diff_handover_days_count,
	ROUND(PERCENTILE_CONT(0.9) WITHIN GROUP (ORDER BY handover_days)::numeric, 2) AS p90_handover_days,
	COUNT(*) - COUNT(transit_days) AS diff_transit_days_count,
	ROUND(PERCENTILE_CONT(0.9) WITHIN GROUP (ORDER BY transit_days)::numeric, 2) AS p90_transit_days,
	ROUND(PERCENTILE_CONT(0.9) WITHIN GROUP (ORDER BY delivery_days)::numeric, 2) AS p90_delivery_days
FROM delivered_orders
WHERE purchase_month >= '2017-12-01' AND purchase_month < '2018-05-01'
GROUP BY purchase_month
ORDER BY purchase_month;

